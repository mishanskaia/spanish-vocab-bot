import os
import json
from anthropic import Anthropic

client = Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
MODEL = "claude-sonnet-4-6"

SYSTEM_PROMPT = (
    "Ты — помощник по изучению испанского языка для начинающих (уровень A1-A2). "
    "Объясняй слова на русском языке. "
    "Отвечай ТОЛЬКО валидным JSON без markdown и без вступления."
)


def _ask_claude(prompt: str, max_tokens: int = 2500):
    response = client.messages.create(
        model=MODEL,
        max_tokens=max_tokens,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": prompt}],
    )
    text = response.content[0].text.strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
    return json.loads(text.strip())


MNEMONIC_SYSTEM_PROMPT = """Ты помогаешь русскоговорящему запомнить испанское слово через мнемонику. Действуй по шагам.

ШАГ 1 — Разбей слово на 2-3 звуковых куска, покрывающих слово ЦЕЛИКОМ от начала до конца (не только середину или хвост — начало тоже нужна зацепка).
- Кусок с узнаваемым испанским суффиксом (-miento/-ción/-dad/-oso и т.п.) или интернациональным/известным корнем — "бесплатная" зацепка, русское созвучие не нужно.
- Для остальных кусков подбери похожее по звучанию РЕАЛЬНОЕ русское слово или устойчивое выражение
  (кириллица, существует в русском языке) — не выдавай транслитерацию иностранного слова под видом
  русского созвучия. Точность не важна: "horia" ≈ "хорь" — этого достаточно.
- Если приличного русского созвучия нет, а созвучие с английским словом отчётливо сильнее и легче
  для запоминания — используй его, но ВСЕГДА с явной пометкой языка и переводом:
  "nun" (англ. "монашка"). Никогда не выдавай иностранное слово без такой пометки, как будто это
  случайное русское созвучие.
- Если нет ни русского, ни отчётливо более сильного английского созвучия (короткие/служебные слова)
  — не натягивай, переходи к ШАГ 1-Б.

ШАГ 1-Б (fallback, только если ШАГ 1 не дал зацепки) — придумай яркий образ по смыслу слова, без опоры на звучание.

ШАГ 2 — Сшей куски (или образ из ШАГ 1-Б) в ОДНУ сценку, где один образ физически перетекает/превращается в другой (не список предметов рядом!), и встрой само значение слова туда как объект или действие.

Пример: zanahoria (морковь) → za-na = "занавес", ho-ria = "хорёк". Сцена: хорёк высовывается из-за занавеса и грызёт морковку.

Формат ответа (строго, без вступлений). Покажи только финальный результат — ни неудачных попыток созвучия, ни слов "ШАГ"/"fallback"/рассуждений о том, почему выбран этот путь, в ответе быть не должно. Используй ОДИНАРНЫЕ звёздочки для жирного — это Telegram Markdown, не CommonMark:

*Разбор:* [куски → зацепки; если сработал ШАГ 1-Б — просто "образ по смыслу", без объяснений почему]
*Сцена:* [1-2 живых предложения — единый образ]
*Связанные слова:* [через запятую, если есть слова той же семьи/корня, иначе пропусти это поле]

Сжато, разговорно, без академичности. Максимум 5 строк."""


def get_mnemonic(phrase: str, meaning: str, part_of_speech: str = "", avoid: str = None) -> str:
    content = f'Слово/фраза: "{phrase}" — {meaning} ({part_of_speech})'
    if avoid:
        content += (
            f'\n\nЭтот вариант пользователю не подошёл:\n{avoid}\n\n'
            f'Предложи другой — другое разбиение на куски (или другой fallback-образ) и другую сцену, не повторяй прошлый вариант.'
        )
    response = client.messages.create(
        model=MODEL,
        max_tokens=400,
        system=MNEMONIC_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": content}],
    )
    return response.content[0].text.strip()


def check_practice_phrase(phrase: str, meaning: str, transcript: str) -> dict:
    """Evening practice: judge one spoken phrase (already transcribed verbatim by
    stt_helper) that was supposed to use `phrase`. Deliberately strict about not
    "correcting" valid alternatives — false corrections were the main risk the
    llm-council flagged for A1 feedback."""
    prompt = f"""Ученик (уровень A1-A2) тренирует устную речь на испанском. Задание — сказать фразу со словом
"{phrase}" ({meaning}). Ниже — автоматическая дословная транскрипция его голосового: ошибки ученика
в ней сохранены специально.

Транскрипция: "{transcript}"

Правила оценки:
- Оценивай фразу ровно так, как она записана.
- Пунктуация, заглавные буквы и лишние/пропущенные значки ударения (например "fué") — огрехи транскрипции,
  а не ошибки ученика. Не комментируй их.
- Исправляй ТОЛЬКО настоящие ошибки: спряжение, род и согласование, предлоги, неверно выбранное слово,
  русские слова вместо испанских. Если фраза грамматически верна и понятна, но её можно сказать иначе
  или красивее — это НЕ ошибка: is_correct = true, ничего не исправляй.
- Русское слово внутри фразы — это пробел в словаре: в corrected замени его испанским.
- Целевое слово засчитывается в любой форме (спряжение, число, род, с артиклем или без).
- Пол говорящего неизвестен: формы и мужского, и женского рода о себе ("estoy cansado" / "estoy cansada")
  одинаково верны — никогда не исправляй одну на другую.
- Не хвали, если есть ошибка. Если всё верно — без восторгов.
- Если транскрипция пустая, не на испанском или из неё невозможно понять смысл — unclear = true.

Верни JSON строго в таком формате:
{{
  "unclear": false,
  "uses_target_word": true,
  "is_correct": true,
  "corrected": "исправленная фраза на испанском, минимально отличающаяся от исходной (сохрани слова и смысл ученика); null если is_correct = true",
  "explanation": "одно короткое предложение на русском: что не так и почему. Если ошибок нет — пустая строка",
  "too_simple": false,
  "suggestion": "если too_simple — одна короткая подсказка на русском, как усложнить (например: добавь, когда и с кем); иначе null"
}}

- too_simple = true, только если фраза верная, но совсем короткая или шаблонная (примерно до 4 слов,
  вроде "La playa es bonita").
- Если целевое слово не использовано — uses_target_word = false, и скажи об этом в explanation."""
    return _ask_claude(prompt, max_tokens=600)


def explain_word(word: str) -> dict:
    prompt = f"""Пользователь написал: "{word}"

Это может быть слово/фраза НА ИСПАНСКОМ (объясни её как есть) или НА РУССКОМ (сначала подбери самый
частотный, естественный для уровня A1-A2 испанский перевод — если у русского слова несколько значений,
бери самое бытовое, — и дальше объясняй именно этот испанский вариант, как будто его и ввели). В любом
случае результат ниже — всегда про испанское слово/фразу, независимо от того, на каком языке был ввод.

Важные правила:
- Если это существительное — ОБЯЗАТЕЛЬНО включи артикль (el/la): например "la casa", "el coche"
- Если это глагол — ОБЯЗАТЕЛЬНО включи спряжение в настоящем времени (presente de indicativo)
- Уровень объяснений — для начинающего (A1-A2)
- Все объяснения и переводы — на русском языке

Верни JSON строго в таком формате:
{{
  "phrase": "испанское слово с артиклем если существительное, или инфинитив если глагол — всегда испанское, даже если ввод был на русском",
  "meaning": "перевод на русском (1-2 слова или короткая фраза)",
  "part_of_speech": "существительное" | "глагол" | "прилагательное" | "наречие" | "предлог" | "местоимение" | "другое",
  "cefr_level": "A1" | "A2",
  "examples": ["пример предложения 1 (испанский — русский перевод)", "пример предложения 2", "пример предложения 3"],
  "collocations": ["устойчивое словосочетание/фраза с этим словом — перевод", "..."],
  "gerund": null,
  "conjugation": null
}}

- examples — ровно 3 примера предложений.
- collocations — 2-4 самых полезных и частотных устойчивых словосочетания/выражения с этим словом
  (формат "словосочетание — перевод"), реально употребимых на уровне A1-A2. Если для этого слова
  нет ничего значимого — верни пустой массив [].
- Если это глагол — ОБЯЗАТЕЛЬНО включи спряжение в настоящем времени (presente de indicativo) в поле
  conjugation, И форму герундия (gerundio) в поле gerund, например "hablando", "comiendo", "viviendo".
  Если не глагол — conjugation и gerund оба null."""
    return _ask_claude(prompt)
