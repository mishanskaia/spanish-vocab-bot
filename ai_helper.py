import os
import json
from anthropic import Anthropic

client = Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
MODEL = "claude-sonnet-4-6"

SYSTEM_PROMPT = (
    "Ты — помощник по изучению испанского языка для начинающих (уровень A1-A2). "
    "Объясняй слова на русском языке. "
    "Отвечай ТОЛЬКО валидным JSON без markdown и без вступления."
)


def _ask_claude(prompt: str):
    response = client.messages.create(
        model=MODEL,
        max_tokens=1500,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": prompt}],
    )
    text = response.content[0].text.strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
    return json.loads(text.strip())


MNEMONIC_SYSTEM_PROMPT = """Ты помогаешь запомнить испанское слово или фразу через ассоциацию на русском языке.

Дай короткую мнемонику для русскоговорящего, изучающего испанский. Используй ОДИН из способов — выбери тот, что подходит лучше всего для конкретного слова:

1. Морфологический разбор — если слово состоит из узнаваемых частей/корней (особенно если корень общий с известными словами, включая интернационализмы или связанные испанские слова).
2. Звуковая ассоциация — если испанское произношение фонетически напоминает русское слово или фразу, связанную по смыслу.
3. Образ/визуализация — короткая яркая картинка, если ни морфология, ни звучание не дают зацепки.

Формат ответа (строго, без вступлений и лишних пояснений). Используй ОДИНАРНЫЕ звёздочки для жирного — это Telegram Markdown, не CommonMark:

*Разбор:* [1-2 предложения, что лежит в основе слова]
*Зацепка:* [конкретная ассоциация — звук, образ или связка с другим словом]
*Связанные слова:* [если есть слова той же семьи/корня — перечисли через запятую, иначе пропусти это поле]

Пиши сжато, разговорным тоном, без академичности. Максимум 4-5 строк всего."""


def get_mnemonic(phrase: str, meaning: str, part_of_speech: str = "") -> str:
    response = client.messages.create(
        model=MODEL,
        max_tokens=400,
        system=MNEMONIC_SYSTEM_PROMPT,
        messages=[{
            "role": "user",
            "content": f'Слово/фраза: "{phrase}" — {meaning} ({part_of_speech})',
        }],
    )
    return response.content[0].text.strip()


def explain_word(word: str) -> dict:
    prompt = f"""Объясни испанское слово или фразу: "{word}"

Важные правила:
- Если это существительное — ОБЯЗАТЕЛЬНО включи артикль (el/la): например "la casa", "el coche"
- Если это глагол — ОБЯЗАТЕЛЬНО включи спряжение в настоящем времени (presente de indicativo)
- Уровень объяснений — для начинающего (A1-A2)
- Все объяснения и переводы — на русском языке

Верни JSON строго в таком формате:
{{
  "phrase": "слово с артиклем если существительное, или инфинитив если глагол",
  "meaning": "перевод на русском (1-2 слова или короткая фраза)",
  "part_of_speech": "существительное" | "глагол" | "прилагательное" | "наречие" | "предлог" | "местоимение" | "другое",
  "cefr_level": "A1" | "A2",
  "examples": ["пример предложения 1 (испанский — русский перевод)", "пример предложения 2 (испанский — русский перевод)"],
  "conjugation": null
}}

Если это глагол — поле conjugation должно быть строкой с таблицей спряжения:
"yo ..., tú ..., él/ella ..., nosotros ..., ellos/ellas ..."

Если не глагол — conjugation = null"""
    return _ask_claude(prompt)


def find_frequent_words(existing_words: list, count: int = 10) -> list:
    existing_str = ", ".join(existing_words) if existing_words else "нет"
    prompt = f"""Подбери ровно {count} испанских слова, которых ещё нет у пользователя. Отвечай кратко и быстро.

Уже добавленные слова (не повторяй): {existing_str}

Требования:
- Проанализируй уже добавленные слова: определи их уровень сложности и тематику
- Подбери следующую логичную порцию слов — чуть сложнее или шире по теме, но в том же духе
- Если слов мало или нет — бери базовую практичную лексику уровня A1: еда, транспорт, время, эмоции, действия
- Разнообразный микс частей речи: существительные, глаголы, прилагательные, наречия
- Для существительных ОБЯЗАТЕЛЬНО с артиклем (la casa, el coche)
- Для глаголов ОБЯЗАТЕЛЬНО спряжение в настоящем времени
- Все объяснения на русском языке

Верни JSON-массив:
[
  {{
    "phrase": "слово (с артиклем для существительных)",
    "meaning": "перевод на русском",
    "part_of_speech": "существительное" | "глагол" | "прилагательное" | "наречие" | "предлог" | "местоимение" | "другое",
    "cefr_level": "A1" | "A2",
    "examples": ["пример 1 (испанский — русский)", "пример 2 (испанский — русский)"],
    "conjugation": "yo ..., tú ..., él/ella ..., nosotros ..., ellos/ellas ..." или null
  }}
]"""
    result = _ask_claude(prompt)
    return result if isinstance(result, list) else []
